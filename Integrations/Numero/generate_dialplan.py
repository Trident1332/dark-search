#!/usr/bin/env python3
"""Generate an outbound-only, server-allowlisted Numero line dialplan.

No network requests, provider login, credential updates, or deployment are done.
The JSON describes owned caller IDs; it must not contain account passwords.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import sys
from typing import Any
import xml.etree.ElementTree as ET


class ConfigurationError(ValueError):
    """A diagnostic that never includes configured numbers or credentials."""


_IDENTIFIER = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,63}", re.ASCII)
_NANP_DID = re.compile(r"\+1[2-9][0-9]{2}[2-9][0-9]{6}", re.ASCII)
_COUNTRIES = ("us", "ca")


def validate(config: Any) -> dict[str, Any]:
    """Validate the exact schema, returning an independent canonical copy."""
    if not isinstance(config, dict) or set(config) != {"gateway", "authorized_seat", "lines"}:
        raise ConfigurationError("Config requires only gateway, authorized_seat, and lines.")
    for key in ("gateway", "authorized_seat"):
        if not isinstance(config[key], str) or _IDENTIFIER.fullmatch(config[key]) is None:
            raise ConfigurationError(f"{key} requires a 1–64 character SIP identifier (letters, digits, _, ., -).")
    lines = config["lines"]
    if not isinstance(lines, dict) or set(lines) != set(_COUNTRIES):
        raise ConfigurationError("lines requires exactly us and ca.")
    for country in _COUNTRIES:
        if not isinstance(lines[country], str) or _NANP_DID.fullmatch(lines[country]) is None:
            raise ConfigurationError(f"lines.{country} requires a canonical +1 NANP number owned by this account.")
    if lines["us"] == lines["ca"]:
        raise ConfigurationError("The US and Canada caller IDs must be different owned numbers.")
    return {"gateway": config["gateway"], "authorized_seat": config["authorized_seat"],
            "lines": {country: lines[country] for country in _COUNTRIES}}


def _unique_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ConfigurationError("Duplicate JSON keys are not accepted.")
        result[key] = value
    return result


def load_config(path: Path) -> dict[str, Any]:
    if path.stat().st_size > 65536:
        raise ConfigurationError("Config exceeds the 64 KiB limit.")
    try:
        config = json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=_unique_object)
    except (UnicodeError, json.JSONDecodeError) as error:
        raise ConfigurationError("Config must be valid UTF-8 JSON.") from error
    return validate(config)


def verify_gateway(xml: str, gateway: str) -> None:
    """Check an existing gateway without changing or returning its credentials."""
    if len(xml.encode("utf-8")) > 1048576 or "<!DOCTYPE" in xml.upper() or "<!ENTITY" in xml.upper():
        raise ConfigurationError("Gateway XML must be at most 1 MiB and contain no DTD or entities.")
    try:
        document = ET.fromstring(xml)
    except ET.ParseError as error:
        raise ConfigurationError("Gateway XML is not well formed.") from error
    matches = [element for element in document.iter("gateway") if element.get("name") == gateway]
    if len(matches) != 1:
        raise ConfigurationError("Gateway XML must contain exactly one gateway with the configured name.")
    parameters = matches[0].findall("param[@name='caller-id-in-from']")
    if len(parameters) != 1 or parameters[0].get("value", "").lower() != "true":
        raise ConfigurationError("The selected gateway must have one caller-id-in-from parameter set to true.")


def generate(config: Any) -> str:
    """Return a fragment for conf/dialplan/default/20_search_numero_lines.xml.

    The browser supplies a line ID and destination, never a caller-ID number.
    All caller identity values below originate in this server-owned allowlist.
    """
    config = validate(config)
    document = ET.Element("include")
    document.append(ET.Comment(" Generated by Search's Numero integration. Outbound only; keep before numeric 90_* routes. "))
    document.append(ET.Comment(" Requires authenticated internal SIP calls and caller-id-in-from=true on the selected gateway. "))
    for country in _COUNTRIES:
        # Keep the existing Numero trunk's confirmed From-user format: bare
        # country-code digits for caller identity, +E164 for the destination.
        did = config["lines"][country][1:]
        extension = ET.SubElement(document, "extension", {"name": f"search_numero_{country}", "continue": "false"})
        ET.SubElement(extension, "condition", {"field": "${sip_authorized}", "expression": r"\Atrue\z", "break": "on-false"})
        ET.SubElement(extension, "condition", {"field": "${sip_auth_username}",
            "expression": r"\A" + re.escape(config["authorized_seat"]) + r"\z", "break": "on-false"})
        condition = ET.SubElement(extension, "condition", {"field": "destination_number",
            "expression": rf"\Anumero-{country}-([1-9][0-9]{{5,14}})\z", "break": "on-false"})
        for data in (
            f"effective_caller_id_number={did}", f"effective_caller_id_name={did}",
            f"outbound_caller_id_number={did}", f"outbound_caller_id_name={did}",
            "hangup_after_bridge=true", "continue_on_fail=false", "absolute_codec_string=PCMU,PCMA",
            "sip_copy_custom_headers=false",
        ):
            ET.SubElement(condition, "action", {"application": "set", "data": data})
        bridge = (f"{{origination_caller_id_number={did},origination_caller_id_name={did}}}"
                  f"sofia/gateway/{config['gateway']}/+$1@numeroesimapp.com")
        ET.SubElement(condition, "action", {"application": "bridge", "data": bridge})
        ET.SubElement(condition, "action", {"application": "hangup", "data": "NORMAL_CLEARING"})
    # This final extension deliberately has no authentication condition: an
    # unauthorized request or malformed line must terminate, not fall through.
    rejected = ET.SubElement(document, "extension", {"name": "search_numero_reject_unknown", "continue": "false"})
    condition = ET.SubElement(rejected, "condition", {"field": "destination_number", "expression": r"(?i)\Anumero-"})
    ET.SubElement(condition, "action", {"application": "hangup", "data": "CALL_REJECTED"})
    ET.indent(document, space="  ")
    return '<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(document, encoding="unicode") + "\n"


def _write_new(path: Path, content: str) -> None:
    # Avoid replacing a working server file or following a symlink. Operators
    # review and install the candidate separately; generated DIDs stay private.
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
    descriptor = os.open(path, flags, 0o600)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
            stream.write(content)
    except BaseException:
        path.unlink(missing_ok=True)
        raise


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("config", type=Path, help="Private JSON with gateway, authorized_seat, and owned US/Canada DIDs")
    parser.add_argument("--output", type=Path, help="Write a new private XML candidate; refuse existing files")
    parser.add_argument("--gateway-xml", type=Path, help="Also verify caller-id-in-from=true in the existing gateway XML")
    args = parser.parse_args(argv)
    try:
        config = load_config(args.config)
        if args.gateway_xml:
            if args.gateway_xml.stat().st_size > 1048576:
                raise ConfigurationError("Gateway XML exceeds the 1 MiB limit.")
            verify_gateway(args.gateway_xml.read_text(encoding="utf-8"), config["gateway"])
        rendered = generate(config)
        if args.output:
            _write_new(args.output, rendered)
        else:
            sys.stdout.write(rendered)
    except ConfigurationError as error:
        print(f"Numero dialplan: {error}", file=sys.stderr)
        return 2
    except (OSError, UnicodeError):
        # Do not echo configuration, file contents, or filesystem paths.
        print("Numero dialplan: could not read input or create the new output file.", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
